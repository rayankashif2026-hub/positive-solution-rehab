import { timingSafeEqual } from "node:crypto";
import { google } from "googleapis";
import { NextResponse } from "next/server";

import { createSupabaseAdminClient } from "@/lib/supabase/admin";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

type Notification = {
  id: string;
  recipient_email: string;
  subject: string;
  payload: Record<string, unknown>;
};

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function parseNotification(value: unknown): Notification {
  if (!isRecord(value) || !isRecord(value.payload)) {
    throw new Error("The notification queue returned an invalid item.");
  }
  if (
    typeof value.id !== "string" ||
    typeof value.recipient_email !== "string" ||
    typeof value.subject !== "string"
  ) {
    throw new Error("The notification queue returned an incomplete item.");
  }
  return {
    id: value.id,
    recipient_email: value.recipient_email,
    subject: value.subject,
    payload: value.payload,
  };
}

function plainText(payload: Record<string, unknown>): string {
  if (payload.notificationType === "access_request") {
    const fields: Array<[string, string]> = [
      ["Request ID", "requestId"],
      ["Name", "fullName"],
      ["Email", "email"],
      ["Branch", "branch"],
      ["Requested role", "requestedRole"],
      ["Reason", "reason"],
      ["Submitted at", "submittedAt"],
    ];
    return [
      "A new clinic portal access request needs review.",
      "",
      ...fields.map(([label, key]) => `${label}: ${String(payload[key] ?? "Not available")}`),
      "",
      "No account or access has been granted. Review this request in the clinic administration portal.",
      "",
      "This message was generated by Positive Solutions Rehab Center.",
    ].join("\r\n");
  }

  const fields: Array<[string, string]> = [
    ["Name", "fullName"],
    ["Username", "username"],
    ["Account email", "email"],
    ["Role", "role"],
    ["Department", "department"],
    ["Login time (Pakistan)", "loginTimePakistan"],
    ["IP address", "ipAddress"],
    ["Browser", "userAgent"],
    ["Status", "loginStatus"],
  ];
  return [
    "A clinic staff account signed in.",
    "",
    ...fields.map(([label, key]) => `${label}: ${String(payload[key] ?? "Not available")}`),
    "",
    "This message was generated by Positive Solutions Rehab Center.",
  ].join("\r\n");
}

function encodeMessage(
  sender: string,
  recipient: string,
  subject: string,
  body: string,
): string {
  const encodedSubject = `=?UTF-8?B?${Buffer.from(subject, "utf8").toString("base64")}?=`;
  const message = [
    `From: ${sender.replace(/[\r\n]/g, "")}`,
    `To: ${recipient.replace(/[\r\n]/g, "")}`,
    `Subject: ${encodedSubject}`,
    "MIME-Version: 1.0",
    "Content-Type: text/plain; charset=UTF-8",
    "Content-Transfer-Encoding: 8bit",
    "",
    body,
  ].join("\r\n");
  return Buffer.from(message, "utf8")
    .toString("base64")
    .replace(/\+/g, "-")
    .replace(/\//g, "_")
    .replace(/=+$/g, "");
}

function authorized(request: Request, secret: string): boolean {
  const supplied = request.headers.get("authorization") ?? "";
  const expected = `Bearer ${secret}`;
  const suppliedBytes = Buffer.from(supplied);
  const expectedBytes = Buffer.from(expected);
  return (
    suppliedBytes.length === expectedBytes.length &&
    timingSafeEqual(suppliedBytes, expectedBytes)
  );
}

export async function GET(request: Request) {
  const cronSecret = process.env.CRON_SECRET;
  if (!cronSecret) {
    return NextResponse.json({ error: "Notification worker is not configured." }, { status: 503 });
  }
  if (!authorized(request, cronSecret)) {
    return NextResponse.json({ error: "Unauthorized." }, { status: 401 });
  }

  const clientId = process.env.GMAIL_CLIENT_ID;
  const clientSecret = process.env.GMAIL_CLIENT_SECRET;
  const refreshToken = process.env.GMAIL_REFRESH_TOKEN;
  const sender = process.env.GMAIL_USER;
  if (!clientId || !clientSecret || !refreshToken || !sender) {
    return NextResponse.json({ error: "Gmail delivery is not configured." }, { status: 503 });
  }

  const admin = createSupabaseAdminClient();
  const { data: claimed, error: claimError } = await admin.rpc(
    "claim_email_notifications",
    { p_limit: 20 },
  );
  if (claimError) {
    console.error("Could not claim login notifications:", claimError.message);
    return NextResponse.json({ error: "Could not load queued notifications." }, { status: 500 });
  }

  const notifications = (claimed ?? []).map(parseNotification);
  if (!notifications.length) {
    return NextResponse.json({ sent: 0, failed: 0 });
  }

  const oauth = new google.auth.OAuth2(clientId, clientSecret);
  oauth.setCredentials({ refresh_token: refreshToken });
  const gmail = google.gmail({ version: "v1", auth: oauth });
  let sent = 0;
  let failed = 0;

  for (const notification of notifications) {
    const recipientIsValid = /^[^\s@\r\n]+@[^\s@\r\n]+\.[^\s@\r\n]+$/.test(
      notification.recipient_email,
    );
    let deliveryError: string | null = null;

    if (!recipientIsValid) {
      deliveryError = "Invalid notification recipient.";
    } else {
      try {
        await gmail.users.messages.send({
          userId: "me",
          requestBody: {
            raw: encodeMessage(
              sender,
              notification.recipient_email,
              notification.subject,
              plainText(notification.payload),
            ),
          },
        });
      } catch (error) {
        console.error(
          "Gmail notification delivery failed:",
          error instanceof Error ? error.message : "Unknown Gmail API error.",
        );
        deliveryError = "Gmail delivery failed.";
      }
    }

    const { error: updateError } = await admin
      .from("email_notifications")
      .update(
        deliveryError
          ? {
              delivery_status: "failed",
              last_error: deliveryError,
            }
          : {
              delivery_status: "sent",
              sent_at: new Date().toISOString(),
              last_error: null,
            },
      )
      .eq("id", notification.id);
    if (updateError) {
      console.error("Could not update notification status:", updateError.message);
      return NextResponse.json(
        { error: "A notification status could not be updated." },
        { status: 500 },
      );
    }

    if (deliveryError) {
      failed += 1;
    } else {
      sent += 1;
    }
  }

  return NextResponse.json({ sent, failed });
}
